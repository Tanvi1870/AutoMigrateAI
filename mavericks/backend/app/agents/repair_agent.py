"""RepairAgent: a minimal locator (or wait) fix for one failing step, with the repaired code.

The LLM may only choose one of the candidate locators found in the failure-time DOM, by id, and explain why.
It never writes code: the repaired code is regenerated by the KB-driven generator from the canonical test
with exactly one locator (or one wait timeout) changed, and the diff is checked to touch nothing else.
"""

import difflib
import re
from collections.abc import Mapping
from typing import Any

from pydantic import Field

from app.agents.dom_locators import locator_present, parse_dom
from app.generators.base_generator import BaseGenerator
from app.llm.base import TASK_KEY, LLMError, LLMProvider
from app.models.base import StrictCamelModel
from app.models.canonical_test import MASKED_VALUE, CanonicalTestCase, Locator, is_sensitive_name
from app.models.enums import ArtifactKind, ExecutionStatus, LocatorSource, RepairChangeType
from app.models.migration_plan import AdvisoryText
from app.models.migration_result import GeneratedArtifact
from app.models.repair import CandidateLocator, RepairContext, RepairProposal

REPAIR_TASK = "repair_proposal"
REPAIR_PROMPT = """You repair failing UI tests that were migrated to Python.
The user message is a JSON document describing one failing step: the canonical step, the locator that failed,
the execution error, the object repository and the candidate locators found on the page at failure time.
Reply with one JSON object and nothing else, using exactly these keys:
  "diagnosis": what went wrong, in one or two sentences,
  "rootCause": why it went wrong,
  "candidateId": the id of the one candidate that is the same element the step intends to use, or null if none is,
  "confidence": a number from 0 to 1,
  "explanation": why that candidate is the same element.
Only choose from the listed candidates. Do not write code. Do not change what the step does or its data;
if the failure is not caused by a changed locator, reply with "candidateId": null."""
MAX_CONFIDENCE = 0.95
MIN_CANDIDATE_SCORE = 0.3
MAX_WAIT_MS = 300_000
DEFAULT_WAIT_MS = 30_000
# Failures that mean "the element was not found or not usable", by exception class name (Playwright, Selenium).
# Classified by type, never by message text: Playwright puts "waiting for locator" in the call log of every
# failure, including assertion failures on an element that is present.
LOCATOR_ERROR_TYPES = frozenset(
    {
        "TimeoutError",
        "TimeoutException",
        "NoSuchElementException",
        "StaleElementReferenceException",
        "ElementNotInteractableException",
        "ElementNotVisibleException",
    }
)
_ASSERTION_MARKERS = ("assert", "verify")


class RepairNotPossibleError(ValueError):
    """No minimal repair exists that keeps the test intent; the reason says why."""


class AIRepairSuggestion(StrictCamelModel):
    """The only shape the LLM may return for a repair."""

    diagnosis: AdvisoryText
    root_cause: AdvisoryText
    candidate_id: int | None = Field(default=None, ge=0)
    confidence: float = Field(ge=0.0, le=1.0)
    explanation: AdvisoryText


class RepairAgent:
    def __init__(self, llm: LLMProvider | None, generators: Mapping[str, BaseGenerator]) -> None:
        self._llm = llm
        self._generators = generators

    def propose(self, context: RepairContext, test_case: CanonicalTestCase) -> RepairProposal:
        step, execution, locator = context.step, context.execution, context.locator
        generator = self._generators.get(execution.target_framework)
        if generator is None:
            raise RepairNotPossibleError(f"No generator is registered for {execution.target_framework}")
        if execution.status is ExecutionStatus.TIMEOUT:
            raise RepairNotPossibleError("The whole run timed out; that is not a single-step locator problem")
        error_type = (execution.error_type or "").rsplit(".", 1)[-1]
        if error_type not in LOCATOR_ERROR_TYPES:
            raise RepairNotPossibleError(
                f"Step {step.sequence} failed with {execution.error_type or 'an error'}, not a missing element; "
                "changing it could change the test intent"
            )
        if step.object_name is None or locator is None:
            raise RepairNotPossibleError(f"Step {step.sequence} ({step.keyword}) has no locator to repair")
        if any(marker in step.keyword.lower() for marker in _ASSERTION_MARKERS):
            raise RepairNotPossibleError(
                f"Step {step.sequence} ({step.keyword}) is an assertion: pointing it at a different element could "
                f"hide a real defect, so it is never repaired automatically. Check the '{step.object_name}' "
                "object repository entry by hand"
            )

        elements = parse_dom(context.dom_snapshot) if context.dom_snapshot else None
        present = locator_present(elements, locator) if elements is not None else None
        if present:
            if step.keyword == "web_wait":
                return self._wait_proposal(context, test_case, generator)
            raise RepairNotPossibleError(
                f"{locator.strategy}={locator.value} still matches the page, so the failure is not a locator problem"
            )
        if elements is not None and present is None:
            raise RepairNotPossibleError(
                f"A {locator.strategy} locator cannot be checked against the page snapshot, so it cannot be proven "
                f"that {locator.strategy}={locator.value} no longer matches; repair it by hand"
            )
        if not context.available_locators:
            raise RepairNotPossibleError(
                "No DOM snapshot or candidate locators are available; a locator cannot be repaired without guessing"
            )
        return self._locator_proposal(context, test_case, generator)

    def _locator_proposal(
        self, context: RepairContext, test_case: CanonicalTestCase, generator: BaseGenerator
    ) -> RepairProposal:
        step, old = context.step, context.locator
        assert step.object_name is not None and old is not None
        candidate, analysis = self._choose(context)
        new_locator = Locator(
            name=step.object_name,
            strategy=candidate.strategy,
            value=candidate.value,
            source=LocatorSource.AI_REPAIRED,
            confidence=analysis["confidence"],
        )
        repaired = with_locator(test_case, new_locator)
        file, original_code, repaired_code, diff, changed_files = _single_file_change(
            generator.build(test_case), generator.build(repaired), ArtifactKind.PAGE_OBJECT, step.object_name
        )
        affected = [s.sequence for s in test_case.steps if s.object_name == step.object_name]
        return RepairProposal(
            step_sequence=step.sequence,
            change_type=RepairChangeType.LOCATOR,
            diagnosis=analysis["diagnosis"],
            root_cause=analysis["root_cause"],
            proposed_change=f"Change the '{step.object_name}' locator from {old.strategy}={old.value} to {candidate.label}",
            old_value=f"{old.strategy}={old.value}",
            new_value=candidate.label,
            new_locator=new_locator,
            confidence=analysis["confidence"],
            explanation=analysis["explanation"],
            object_name=step.object_name,
            affected_steps=affected,
            file=file,
            changed_files=changed_files,
            original_code=original_code,
            repaired_code=repaired_code,
            code_diff=diff,
            analysis_source=analysis["source"],
        )

    def _wait_proposal(
        self, context: RepairContext, test_case: CanonicalTestCase, generator: BaseGenerator
    ) -> RepairProposal:
        step = context.step
        old_ms = int(step.value) if step.value and step.value.isdigit() else DEFAULT_WAIT_MS
        new_ms = min(old_ms * 2, MAX_WAIT_MS)
        if new_ms <= old_ms:
            raise RepairNotPossibleError(f"Step {step.sequence} already waits the maximum {MAX_WAIT_MS} ms")
        repaired = with_step_value(test_case, step.sequence, str(new_ms))
        file, original_code, repaired_code, diff, changed_files = _single_file_change(
            generator.build(test_case), generator.build(repaired), ArtifactKind.TEST, None
        )
        return RepairProposal(
            step_sequence=step.sequence,
            change_type=RepairChangeType.WAIT,
            diagnosis=f"Step {step.sequence} timed out waiting for '{step.object_name}', which is on the page.",
            root_cause="The element appears later than the configured wait allows.",
            proposed_change=f"Increase the step {step.sequence} wait from {old_ms} ms to {new_ms} ms",
            old_value=step.value or "",
            new_value=str(new_ms),
            confidence=0.6,
            explanation="The locator still matches, so only the wait time of this one step changes.",
            object_name=step.object_name,
            affected_steps=[step.sequence],
            file=file,
            changed_files=changed_files,
            original_code=original_code,
            repaired_code=repaired_code,
            code_diff=diff,
        )

    def _choose(self, context: RepairContext) -> tuple[CandidateLocator, dict[str, Any]]:
        candidates = {c.candidate_id: c for c in context.available_locators}
        best = max(context.available_locators, key=lambda c: c.score)
        note = ""
        if self._llm is not None:
            try:
                suggestion = self._llm.generate_json(REPAIR_PROMPT, llm_context(context), AIRepairSuggestion)
            except LLMError as exc:
                note = f" (AI analysis unavailable: {exc})"
            else:
                if suggestion.candidate_id is None:
                    raise RepairNotPossibleError(f"AI analysis found no matching element: {suggestion.diagnosis}")
                chosen = candidates.get(suggestion.candidate_id)
                # The LLM must meet the same similarity floor as the heuristic: page text can try to steer it.
                if chosen is not None and chosen.score >= MIN_CANDIDATE_SCORE:
                    return chosen, {
                        "diagnosis": suggestion.diagnosis,
                        "root_cause": suggestion.root_cause,
                        "explanation": suggestion.explanation,
                        "confidence": round(min(suggestion.confidence, MAX_CONFIDENCE), 2),
                        "source": "mock" if self._llm.name == "mock" else "llm",
                    }
                note = " (the AI suggestion did not match a sufficiently similar element on the page and was ignored)"
        if best.score < MIN_CANDIDATE_SCORE:
            raise RepairNotPossibleError(f"No element on the page resembles '{context.step.object_name}'")
        return best, _heuristic_analysis(context, best, note)


def _heuristic_analysis(context: RepairContext, candidate: CandidateLocator, note: str) -> dict[str, Any]:
    step, old, execution = context.step, context.locator, context.execution
    assert old is not None
    element = f"{candidate.tag} '{candidate.text}'" if candidate.text else candidate.tag
    return {
        "diagnosis": (
            f"Step {step.sequence} ({step.keyword} {step.object_name}) failed with {execution.error_type}: "
            f"{old.strategy}={old.value} no longer matches any element on the page."
        ),
        "root_cause": f"The application changed the {element}; it is now located by {candidate.label}.",
        "explanation": (
            f"{candidate.label} is the {element} that best matches '{step.object_name}' "
            f"(similarity {candidate.score:.0%}). Only this locator changes; actions and data stay the same.{note}"
        ),
        "confidence": round(min(0.5 + 0.45 * candidate.score, MAX_CONFIDENCE), 2),
        "source": "heuristic",
    }


def llm_context(context: RepairContext) -> dict[str, Any]:
    step, execution = context.step, context.execution
    value = step.value
    if value is not None and step.object_name and is_sensitive_name(step.object_name):
        value = MASKED_VALUE
    return {
        TASK_KEY: REPAIR_TASK,
        "step": {"sequence": step.sequence, "keyword": step.keyword, "object": step.object_name, "value": value},
        "failedLocator": f"{context.locator.strategy}={context.locator.value}" if context.locator else None,
        "error": {"type": execution.error_type, "message": (execution.error_message or "")[:500]},
        "objectRepository": {name: f"{loc.strategy}={loc.value}" for name, loc in context.object_repository.items()},
        "candidates": [
            {"id": c.candidate_id, "locator": c.label, "tag": c.tag, "text": c.text, "score": c.score}
            for c in context.available_locators
        ],
        "stepCode": _step_code(context.generated_code, step.sequence),
    }


def with_locator(test_case: CanonicalTestCase, locator: Locator) -> CanonicalTestCase:
    data = test_case.model_dump(by_alias=True)
    data["objectRepository"][locator.name] = locator.model_dump(by_alias=True)
    return CanonicalTestCase.model_validate(data)


def with_step_value(test_case: CanonicalTestCase, sequence: int, value: str) -> CanonicalTestCase:
    data = test_case.model_dump(by_alias=True)
    for step in data["steps"]:
        if step["sequence"] == sequence:
            step["value"] = value
    return CanonicalTestCase.model_validate(data)


def _single_file_change(
    before: list[GeneratedArtifact], after: list[GeneratedArtifact], kind: ArtifactKind, object_name: str | None
) -> tuple[str, str, str, str, list[str]]:
    """The repair changes one file of the expected kind, and only the lines for that one change.

    For a locator change, a test file may also change, but only in its Selenium `By.<strategy>` constants.
    Returns (main file, its original code, its repaired code, unified diff of every changed file, changed files).
    """
    old = {a.path: a for a in before}
    new = {a.path: a for a in after}
    changed = sorted(p for p in old.keys() | new.keys() if p not in old or p not in new or old[p].content != new[p].content)
    if any(p not in old or p not in new for p in changed):
        raise RepairNotPossibleError("The repair would add or remove generated files")
    main = [p for p in changed if new[p].kind is kind]
    others = [p for p in changed if new[p].kind is not kind]
    strategy_only = all(
        object_name and new[p].kind is ArtifactKind.TEST and _without_by(old[p].content) == _without_by(new[p].content)
        for p in others
    )
    if len(main) != 1 or not strategy_only:
        raise RepairNotPossibleError(f"The repair would change {changed or 'nothing'}; only one {kind} file may change")
    path = main[0]
    original, repaired = old[path].content, new[path].content
    edits = [line for line in difflib.ndiff(original.splitlines(), repaired.splitlines()) if line[:2] in ("- ", "+ ")]
    removed, added = (sum(line.startswith(sign) for line in edits) for sign in ("- ", "+ "))
    limit = 2 if object_name else 1  # a locator change edits its comment and its constant; a wait edits one call
    if removed > limit or added > limit:
        raise RepairNotPossibleError(f"The repair would change {removed + added} lines in {path}; it must be minimal")
    if object_name and not all(
        line[2:].strip().startswith(f"# {object_name}:") or re.match(r"\s+[A-Z][A-Z0-9_]* = ", line[2:]) for line in edits
    ):
        raise RepairNotPossibleError(f"The repair would change lines unrelated to '{object_name}' in {path}")
    diff = "".join(
        "".join(
            difflib.unified_diff(
                old[p].content.splitlines(keepends=True), new[p].content.splitlines(keepends=True), f"a/{p}", f"b/{p}"
            )
        )
        for p in [path, *others]
    )
    return path, original, repaired, diff, [path, *others]


def _without_by(source: str) -> str:
    return re.sub(r"\bBy\.[A-Z_]+\b", "By.*", source)


def _step_code(source: str, sequence: int) -> str:
    lines = source.splitlines()
    marker = re.compile(r"^\s*#\s*\[AM-STEP (\d+)\]")
    start = next((i for i, line in enumerate(lines) if (m := marker.match(line)) and int(m.group(1)) == sequence), None)
    if start is None:
        return ""
    end = next((i for i in range(start + 1, len(lines)) if marker.match(lines[i])), len(lines))
    return "\n".join(lines[start:end])
